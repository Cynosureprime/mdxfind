/*
 * hx8_to_c.c -- build-time tool that converts the hx.8 algorithm
 *               catalog into codegen/hx_specs_data.c, a C-literal
 *               serialization of pre-compiled hx_program structs.
 *
 * Per spec D12.2.c REVISED-AGAIN (Path A) from
 * ~/.claude/projects/-Users-dlr-src-mdfind/memory/
 *   project_hx_codegen_phase2_3_spec_2026-05-21.md:
 *
 *   1. Open hx.8 (path via argv[1]); skip troff header before first eN row.
 *   2. For each `eN<TAB>NAME<TAB>EXPRESSION_OR_MARKUP` row:
 *      - detect outlier (\fI italics, T{ table block, \(em see Note)
 *      - non-outlier: strip remaining troff escapes, call hx_compile_expr
 *      - on success: serialize resulting hx_program to C literal
 *      - on compile failure: warn to stderr, mark compile_failed=1
 *   3. Emit codegen/hx_specs_data.c with:
 *      - banner: AUTO-GENERATED by tools/hx8_to_c -- DO NOT EDIT
 *      - per-entry static const initializers (code[], strings[], etc.)
 *      - top-level const struct hx_spec_entry hx_specs_data[] array
 *      - per-entry comment block with original expression + hx.8 line
 *   4. Summary report to stderr.
 *   5. exit(0) on success (any non-fatal soft-failures), nonzero only
 *      on truly fatal errors (hx.8 missing, output write failure).
 *
 * The tool links against the existing hx library ($(HX_OBJS)) plus
 * hashpipe.o (for hx_register_hashpipe_types(), which registers the
 * full 994-primitive function table before hx_compile_expr is invoked).
 *
 * mdxfind itself contains NO hx parser; only the compiled-in
 * hx_specs_data[] array. The tool runs at make time on the build host.
 *
 * Sub-phase 5a.1 (2026-05-22): each emitted hx_spec_entry initializer
 * now also includes a .call_names pointer at the per-program
 * _hx_callnames_NNN[] sidecar (already emitted earlier in the same
 * file). NULL for outliers / compile-fails. Enables codegen emitters
 * to resolve per-call-site function names via hx_callname_for_entry.
 *
 * 1.1
 * hx8_to_c.c,v
 * Revision 1.1  2026/05/21 23:22:54  dlr
 * sub-phase 2a.2: build-time tool that reads hx.8 and emits codegen/hx_specs_data.c. Per spec D12.2.c Path A: links existing hx library via -DHX_STANDALONE -DHX_NO_MAIN; pre-scans expressions to stub-register unknown function names so hx_compile_expr never hits its exit-1 path; serializes resulting hx_program to C literal. 994 entries total: 781 non-outlier success, 210 outlier, 3 compile-fail (NTLM and another with bracket footnote, e522 with extra closing paren).
 *
 */

